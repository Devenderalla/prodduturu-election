  function t(key, vars) {
    var table = DICT[lang] || DICT.en;
    var s = table[key];
    if (s == null) s = DICT.en[key];
    if (s == null) return key;
    if (vars) {
      Object.keys(vars).forEach(function (k) {
        s = s.split('{' + k + '}').join(String(vars[k]));
      });
    }
    return s;
  }

